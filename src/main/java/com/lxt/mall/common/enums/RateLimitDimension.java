package com.lxt.mall.common.enums;

/**
 * 限流维度。
 *
 * <p>单维度限流都不够用，本项目做的是【多维度叠加】：
 * <pre>
 *   IP    —— 挡住单机刷接口（脚本/压测工具），但挡不住 IP 池
 *   USER  —— 挡住单账号刷接口，是最可靠的一维（登录成本高）
 *   API   —— 保护单个接口不被整体打垮（全局兜底）
 * </pre>
 * 秒杀接口三道全开；商品详情只开 IP + API，因为它是读接口，
 * 按用户维度限流意义不大（未登录也能看）。
 */
public enum RateLimitDimension {

    /** 全局（不区分调用方），保护接口自身。 */
    API,

    /** 按用户ID，最可靠的一维。 */
    USER,

    /** 按客户端 IP。 */
    IP,

    /** 全局总量。 */
    GLOBAL
}
